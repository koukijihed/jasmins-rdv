let langue = "fr";
const listeners = new Set();

export const LANGS = ["fr", "ar"];

export function getLang() {
  return langue;
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  langue = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars) {
  const value = DICT[langue]?.[key] ?? DICT.fr[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] ?? m));
}

export function locale() {
  return langue === "ar" ? "ar-TN" : "fr-TN";
}

/** Date ISO (yyyy-mm-dd) → texte localisé court, ex. « lun. 24 nov. » */
export function fmtDate(iso, opts = {}) {
  if (!iso) return "";
  const d = parseISODate(iso);
  const base = { weekday: opts.weekday ?? "short", day: "2-digit", month: "short" };
  if (opts.year) base.year = "numeric";
  try {
    return new Intl.DateTimeFormat(locale(), base).format(d);
  } catch {
    return iso;
  }
}

export function fmtDateLong(iso) {
  if (!iso) return "";
  const d = parseISODate(iso);
  try {
    return new Intl.DateTimeFormat(locale(), {
      weekday: "long",
      day: "numeric",
      month: "long",
      year: "numeric",
    }).format(d);
  } catch {
    return iso;
  }
}

export function fmtDateTime(isoInstant) {
  if (!isoInstant) return "";
  const d = new Date(isoInstant);
  try {
    return new Intl.DateTimeFormat(locale(), {
      day: "2-digit",
      month: "short",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
      hour12: false,
    }).format(d);
  } catch {
    return isoInstant;
  }
}

export function fmtTime(isoInstant) {
  if (!isoInstant) return "";
  const d = new Date(isoInstant);
  try {
    return new Intl.DateTimeFormat(locale(), { hour: "2-digit", minute: "2-digit", hour12: false }).format(d);
  } catch {
    return isoInstant;
  }
}

export function fmtNumber(n, digits = 0) {
  try {
    return new Intl.NumberFormat(locale(), {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    }).format(n);
  } catch {
    return String(n);
  }
}

export function parseISODate(iso) {
  const [y, m, d] = String(iso).split("-").map(Number);
  return new Date(y, (m || 1) - 1, d || 1, 12, 0, 0, 0);
}

